"""Evaluation on 30 ideas with a known prior paper each (eval/ideas.json).

Usage:  python eval/evaluate.py      (needs eval/rewrites.json from make_rewrites.py)

The 30 target papers were drawn at random from the store (seed 114, 10 per primary
category cs.AR / cs.CV / cs.LG). Each has a casual description that avoids the paper's
own terms and a technical one. A hit means the target paper is in the top k.

Writes eval/results.md (generated, don't edit by hand).
"""
import json
import os
import re
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from chromadb.utils.embedding_functions import DefaultEmbeddingFunction  # noqa: E402

import novelty  # noqa: E402
from db import ARXIV, get_collection  # noqa: E402

HERE = os.path.join(ROOT, "eval")
GATE = 0.56  # midpoint of the gap between good (max 0.52) and totally drifted (min 0.60) rewrites
LABELS = ["OUT OF SCOPE", "LOOKS OPEN (in this collection)", "RELATED WORK EXISTS", "CROWDED", "VERY CLOSE MATCH"]
NONSENSE = ["my grandmother's lasagna recipe for a dinner party", "best hiking trails in Colorado",
            "how to train my puppy to sit", "the fall of the Roman empire",
            "filing my taxes before the deadline", "how to knit a wool scarf"]
STOP = set("a an the of to and or for in on at by with from so it its it's is are be can that this into after "
           "before without but one ones what how do does make making than more most very their they them our "
           "we using use used based via new".split())

out = []


def emit(line=""):
    print(line)
    out.append(line)


def unit(x):
    x = np.asarray(x, dtype=np.float32)
    return x / np.linalg.norm(x, axis=-1, keepdims=True)


def words(text):
    return {w for w in re.findall(r"[a-z0-9]+", text.lower()) if w not in STOP and len(w) > 2}


def ranks_of(dist, targets):
    """1-based rank of each row's target paper (ties count against it)."""
    return np.array([1 + int((row < row[t]).sum()) for row, t in zip(dist, targets)])


def rank_matrix(dist):
    order = np.argsort(dist, axis=1)
    r = np.empty_like(order)
    rows = np.arange(dist.shape[0])[:, None]
    r[rows, order] = np.arange(1, dist.shape[1] + 1)
    return r


def summarize(r):
    return f"{(r <= 5).sum()}/30", f"{(r <= 10).sum()}/30", f"{np.mean(1 / r):.3f}"


def verdict(d, calib):
    return novelty.assess(float(d), calib)["label"]


def main():
    np.seterr(all="ignore")  # numpy 2.0 + macOS Accelerate emits spurious matmul warnings; checked vs float64
    col = get_collection()
    calib = novelty.load_calibration(col)
    got = col.get(where={"source": ARXIV}, include=["embeddings", "documents"])
    ids, E, docs = got["ids"], unit(got["embeddings"]), got["documents"]
    idx = {pid: i for i, pid in enumerate(ids)}

    with open(os.path.join(HERE, "ideas.json")) as f:
        ideas = json.load(f)
    with open(os.path.join(HERE, "rewrites.json")) as f:
        rw = json.load(f)
    assert [r["target"] for r in rw["rewrites"]] == [i["target"] for i in ideas]
    targets = np.array([idx[i["target"]] for i in ideas])

    ef = DefaultEmbeddingFunction()
    emb = lambda texts: unit(ef(texts))  # noqa: E731
    C = emb([i["casual"] for i in ideas])
    T = emb([i["technical"] for i in ideas])
    G = emb([r["good"] for r in rw["rewrites"]])
    D = emb([r["drifted"] for r in rw["rewrites"]])
    S = np.roll(G, 1, axis=0)  # every idea paired with a different idea's rewrite: total drift
    dist = {k: 1 - Q @ E.T for k, Q in dict(casual=C, technical=T, good=G, drifted=D, shuffled=S).items()}

    # sanity: numpy distances match what Chroma returns
    chroma = col.query(query_texts=[ideas[0]["casual"]], n_results=1, where={"source": ARXIV}, include=["distances"])
    assert abs(chroma["distances"][0][0] - dist["casual"][0].min()) < 1e-3, "numpy and Chroma disagree"

    overlap = [len(words(i["casual"]) & words(docs[idx[i["target"]]])) for i in ideas]
    emit("# Evaluation results (generated by eval/evaluate.py)")
    emit()
    emit(f"30 ideas, one known target paper each, drawn at random from the {len(ids):,}-paper store. "
         f"Rewrites by {rw['model']} with the app's own prompt.")
    emit(f"Casual descriptions share a median of {int(np.median(overlap))} content words with their target "
         f"(max {max(overlap)}); {sum(o == 0 for o in overlap)}/30 share none.")

    # ---- 1. retrieval: hit@5 by strategy -------------------------------------------------
    Qs = dict(good=G, drifted=D, shuffled=S)

    def fused(rewrite_key):
        Dc, Dr = dist["casual"], dist[rewrite_key]
        rrf = -(1 / (60 + rank_matrix(Dc)) + 1 / (60 + rank_matrix(Dr)))
        keep = (1 - np.sum(C * Qs[rewrite_key], axis=1)) < GATE  # drift gate, see section 3
        gated = np.where(keep[:, None], np.minimum(Dc, Dr), Dc)
        return {"merged: min (current app)": np.minimum(Dc, Dr), "merged: RRF (k=60)": rrf,
                "merged: weighted 0.5/0.5": 0.5 * Dc + 0.5 * Dr,
                "merged: weighted 0.7 user / 0.3 rewrite": 0.7 * Dc + 0.3 * Dr,
                f"gate (drop rewrite if > {GATE}) + min": gated}

    emit()
    emit("## 1. Does the target paper come back? (good rewrites)")
    emit()
    emit("| search | hit@5 | hit@10 | MRR |")
    emit("|---|---|---|---|")
    base = {"vector-only (casual words)": dist["casual"], "rewrite-only": dist["good"]}
    for name, d in {**base, **fused("good")}.items():
        emit(f"| {name} | " + " | ".join(summarize(ranks_of(d, targets))) + " |")
    Dc, Dg = dist["casual"], dist["good"]
    top5 = np.argsort(np.minimum(Dc, Dg), axis=1)[:, :5]
    from_rw = np.mean([Dg[i, j] < Dc[i, j] for i in range(30) for j in top5[i]])
    emit(f"| _reference: technical description, vector-only_ | " +
         " | ".join(summarize(ranks_of(dist["technical"], targets))) + " |")

    emit()
    emit(f"In the current min() fusion, {from_rw:.0%} of top-5 papers get their score from the rewrite, not the user's words: "
         f"rewrite distances run lower (median nearest {np.median(Dg.min(axis=1)):.3f} vs {np.median(Dc.min(axis=1)):.3f}), "
         "so min() is effectively rewrite-only.")

    # ---- 2. robustness: what a bad rewrite does to each fusion ---------------------------
    casual_top20 = np.argsort(dist["casual"], axis=1)[:, :20]
    emit()
    emit("## 2. When the rewrite is bad")
    emit()
    emit("hit@5 with each kind of rewrite, and how many of the top-5 slots (out of 150) are taken by papers "
         "that are not even in the casual query's top 20, i.e. pulled in by the rewrite alone.")
    emit()
    emit("| fusion | hit@5 good | hit@5 mild drift | hit@5 total drift | rewrite-only slots: good / mild / total |")
    emit("|---|---|---|---|---|")
    vec_hits = (ranks_of(dist["casual"], targets) <= 5).sum()
    per_kind = {k: fused(k) for k in ("good", "drifted", "shuffled")}
    for name in per_kind["good"]:
        hits, slots = [], []
        for k in ("good", "drifted", "shuffled"):
            d = per_kind[k][name]
            hits.append(f"{(ranks_of(d, targets) <= 5).sum()}/30")
            top5 = np.argsort(d, axis=1)[:, :5]
            slots.append(str(sum(len(set(t) - set(c)) for t, c in zip(top5, casual_top20))))
        emit(f"| {name} | " + " | ".join(hits) + " | " + " / ".join(slots) + " |")
    emit(f"| _vector-only, no rewrite_ | {vec_hits}/30 | {vec_hits}/30 | {vec_hits}/30 | 0 / 0 / 0 |")

    emit()
    emit("Verdict changes caused by the rewrite (vs. vector-only verdict), out of 30:")
    emit()
    emit("| fusion | good rewrite | mild drift | total drift |")
    emit("|---|---|---|---|")
    v_vec = [verdict(d, calib) for d in dist["casual"].min(axis=1)]
    for name in ["merged: min (current app)", "merged: weighted 0.5/0.5", "merged: weighted 0.7 user / 0.3 rewrite"]:
        row = []
        for k in ("good", "drifted", "shuffled"):
            v = [verdict(d, calib) for d in per_kind[k][name].min(axis=1)]
            row.append(str(sum(a != b for a, b in zip(v, v_vec))))
        emit(f"| {name} | " + " | ".join(row) + " |")
    emit()
    for name in ["merged: min (current app)", f"gate (drop rewrite if > {GATE}) + min", "merged: weighted 0.7 user / 0.3 rewrite"]:
        d = per_kind["shuffled"][name]
        top1 = d.argmin(axis=1)
        fake = sum(verdict(d[i].min(), calib) == "VERY CLOSE MATCH" and top1[i] not in casual_top20[i] for i in range(30))
        emit(f"- {name}: with a totally wrong rewrite, {fake}/30 ideas get VERY CLOSE MATCH for a paper outside the casual top 20")

    # ---- 3. drift check: distance between the idea and its rewrite ------------------------
    d_self = {k: 1 - np.sum(C * Q, axis=1) for k, Q in dict(good=G, drifted=D, shuffled=S, technical=T).items()}
    emit()
    emit("## 3. Rewrite drift: cosine distance between the user's idea and the rewrite")
    emit()
    emit("| pair | min | median | max |")
    emit("|---|---|---|---|")
    for k, label in [("technical", "my technical description (human, faithful)"), ("good", "good LLM rewrite"),
                     ("drifted", "LLM asked to drift (mild)"), ("shuffled", "another idea's rewrite (total drift)")]:
        v = d_self[k]
        emit(f"| {label} | {v.min():.3f} | {np.median(v):.3f} | {v.max():.3f} |")
    emit()
    emit(f"Any cutoff between {d_self['good'].max():.2f} and {d_self['shuffled'].min():.2f} separates good from "
         f"totally drifted rewrites perfectly. The gate uses the midpoint, **X = {GATE}**: keeps "
         f"{(d_self['good'] < GATE).sum()}/30 good, rejects {(d_self['shuffled'] >= GATE).sum()}/30 total drift and "
         f"{(d_self['drifted'] >= GATE).sum()}/30 mild drift.")
    gain = ranks_of(dist["casual"], targets) - ranks_of(dist["good"], targets)
    helped = gain > 20
    emit(f"Rewrites that moved the target up more than 20 places: {helped.sum()}; their idea-rewrite distance: "
         f"median {np.median(d_self['good'][helped]):.3f} (max {d_self['good'][helped].max():.3f}) vs "
         f"{np.median(d_self['good'][~helped]):.3f} for the rest. Faithful human restatements exceed {GATE} in "
         f"{(d_self['technical'] >= GATE).sum()}/30 cases, so the gate is tuned to this LLM's wording style.")
    own = sum(int(np.argmin(1 - G[i] @ C.T)) == i for i in range(30))
    emit(f"Relative check: a good rewrite is closer to its own idea than to any of the other 29 ideas in {own}/30 cases.")

    # ---- 4. casual vs technical: the distance gap ------------------------------------------
    dmin_c, dmin_t = dist["casual"].min(axis=1), dist["technical"].min(axis=1)
    dtar_c = dist["casual"][np.arange(30), targets]
    dtar_t = dist["technical"][np.arange(30), targets]
    gap = dmin_c - dmin_t
    emit()
    emit("## 4. Casual vs technical wording: the distance gap")
    emit()
    emit("| | casual | technical | gap (casual - technical) |")
    emit("|---|---|---|---|")
    emit(f"| distance to nearest paper, median | {np.median(dmin_c):.3f} | {np.median(dmin_t):.3f} | "
         f"{np.median(gap):.3f} (sd {gap.std():.3f}, range {gap.min():.3f} to {gap.max():.3f}) |")
    emit(f"| distance to the target paper, median | {np.median(dtar_c):.3f} | {np.median(dtar_t):.3f} | "
         f"{np.median(dtar_c - dtar_t):.3f} |")
    v_c = [verdict(d, calib) for d in dmin_c]
    v_t = [verdict(d, calib) for d in dmin_t]
    shift = float(np.median(gap))
    v_c_shift = [verdict(d - shift, calib) for d in dmin_c]
    v_t_shift = [verdict(d - shift, calib) for d in dmin_t]
    v_merged = [verdict(d, calib) for d in np.minimum(dist["casual"], dist["good"]).min(axis=1)]
    nonsense = 1 - emb(NONSENSE) @ E.T
    ns_shift = [verdict(d - shift, calib) for d in nonsense.min(axis=1)]
    agree = lambda a, b: sum(x == y for x, y in zip(a, b))  # noqa: E731
    emit()
    emit("Verdict agreement with the technical description's verdict (30 ideas):")
    emit()
    emit(f"- casual, vector-only, current thresholds: {agree(v_c, v_t)}/30")
    emit(f"- casual + good rewrite (current app with a key): {agree(v_merged, v_t)}/30")
    emit(f"- casual, thresholds shifted by the median gap ({shift:.3f}): {agree(v_c_shift, v_t)}/30")
    emit(f"- cost of that shift for someone who writes technically without a key: their verdict changes in "
         f"{30 - agree(v_t_shift, v_t)}/30 cases")
    emit(f"- nonsense queries still OUT OF SCOPE after the shift: {sum(v == 'OUT OF SCOPE' for v in ns_shift)}/6")
    hide = lambda d: np.where(np.arange(d.shape[1])[None, :] == targets[:, None], np.inf, d)  # noqa: E731
    h_c, h_t = hide(dist["casual"]).min(axis=1), hide(dist["technical"]).min(axis=1)
    hv_t = [verdict(d, calib) for d in h_t]
    emit()
    emit("Same test with each target paper hidden (an idea whose exact paper isn't in the store):")
    emit()
    emit(f"- casual vs technical agreement, current thresholds: {agree([verdict(d, calib) for d in h_c], hv_t)}/30; "
         f"shifted: {agree([verdict(d - shift, calib) for d in h_c], hv_t)}/30")
    emit(f"- cost of the shift for technical writers without a key: verdict changes in "
         f"{30 - agree([verdict(d - shift, calib) for d in h_t], hv_t)}/30 cases")
    emit()
    emit("Verdict distribution (casual / technical / casual+rewrite): " + "; ".join(
        f"{lab.split(' (')[0]} {v_c.count(lab)}/{v_t.count(lab)}/{v_merged.count(lab)}" for lab in reversed(LABELS)))

    with open(os.path.join(HERE, "results.md"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
